# Update heroGuidesData.js
with open('src/data/heroGuidesData.js', 'r', encoding='utf-8') as f:
    text = f.read()

# Parse JSON inside file
match = re.search(r'export const HERO_GUIDES = ({[\s\S]+});', text)
if match:
    data = json.loads(match.group(1))
    for hid, info in S_PLUS_PLUS_HEROES.items():
        data[hid] = info
    
    new_js = f'''/* ======================================================================
   HERO WARS — COMPREHENSIVE HERO GUIDES DATABASE (alexandregames.com)
   ====================================================================== */

export const HERO_GUIDES = {json.dumps(data, ensure_ascii=False, indent=2)};

export function getHeroGuide(heroId) {{
  return HERO_GUIDES[heroId] || HERO_GUIDES['electra'];
}}
'''
    with open('src/data/heroGuidesData.js', 'w', encoding='utf-8') as out:
        out.write(new_js)
    print('✓ Updated S++ heroes in src/data/heroGuidesData.js!')
