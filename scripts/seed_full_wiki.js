async function seedFullWiki() {
  console.log(`Starting enriched proofread seed for ${FULL_HEROES.length} heroes...`);

  // Delete existing
  const { error: delErr } = await supabase.from('hw_heroes').delete().neq('id', '___none___');
  if (delErr) {
    console.error('Failed to clear hw_heroes:', delErr.message);
  }

  // Insert in batches of 10
  for (let i = 0; i < FULL_HEROES.length; i += 10) {
    const chunk = FULL_HEROES.slice(i, i + 10).map(h => {
      const pngPath = join(__dirname, `../public/assets/heroes/${h.id}.png`);
      let ext = 'png';
      if (existsSync(pngPath)) {
        const buf = readFileSync(pngPath);
        if (buf.length < 2000 || buf[0] === 0x3C) { // <svg
          ext = 'svg';
        }
      }
      return {
        ...h,
        avatar_url: `/assets/heroes/${h.id}.${ext}`
      };
    });
    const { error } = await supabase.from('hw_heroes').insert(chunk);
    if (error) {
      console.error(`Batch ${i/10 + 1} insert failed:`, error.message);
    } else {
      console.log(`✓ Inserted batch ${i/10 + 1} (${chunk.length} heroes with enriched formulas & artifact stats)`);
    }
  }

  console.log('🎉 Enriched Hero Wars Wiki seed complete!');
}

seedFullWiki();
