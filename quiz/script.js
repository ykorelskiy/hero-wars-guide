const container = document.getElementById('quizContainer');
const searchInput = document.getElementById('searchInput');

function renderQuiz(data) {
    container.innerHTML = '';
    
    if (data.length === 0) {
        container.innerHTML = '<div class="empty-state">Вопрос не найден. Попробуй ввести одно самое редкое слово из вопроса.</div>';
        return;
    }

    data.forEach(item => {
        const div = document.createElement('div');
        div.className = 'quiz-item';
        div.innerHTML = `
            <div class="question">${item.q}</div>
            <div class="answer">Ответ: ${item.a}</div>
        `;
        container.appendChild(div);
    });
}

renderQuiz(quizData);

searchInput.addEventListener('input', (e) => {
    // Разбиваем запрос на отдельные слова для более умного поиска
    const searchTerms = e.target.value.toLowerCase().trim().split(' ');
    
    const filteredData = quizData.filter(item => {
        const textToSearch = (item.q + " " + item.a).toLowerCase();
        // Проверяем, что КАЖДОЕ введенное слово есть в вопросе или ответе
        return searchTerms.every(term => textToSearch.includes(term));
    });
    
    renderQuiz(filteredData);
});