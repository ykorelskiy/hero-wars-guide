async function run() {
  const { data: heroData } = await supabase.from('hw_heroes').select('guide').eq('id', 'byrna').single();
  const newGuide = { ...heroData.guide, ...byrnaUpdates };
  
  const { error } = await supabase.from('hw_heroes').update({ guide: newGuide }).eq('id', 'byrna');
  if (error) console.error(error);
  else console.log('Successfully updated Byrna guide!');
}
run();
