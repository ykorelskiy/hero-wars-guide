async function updateHero(slug, updates) {
  const { data: heroData } = await supabase.from('hw_heroes').select('guide').eq('id', slug).single();
  const newGuide = { ...heroData.guide, ...updates };
  const { error } = await supabase.from('hw_heroes').update({ guide: newGuide }).eq('id', slug);
  if (error) console.error(`Error updating ${slug}:`, error);
  else console.log(`Successfully updated ${slug} guide!`);
}

async function run() {
  await updateHero('dante', danteUpdates);
  await updateHero('amira', amiraUpdates);
  await updateHero('fluffy', fluffyUpdates);
}
run();
