async function updateHeroes() {
  for (const hero of manualData) {
    const { error } = await supabase
      .from('hw_heroes')
      .update({
        skills: hero.skills,
        guide: hero.guide
      })
      .eq('id', hero.id);
      
    if (error) {
      console.error('Error updating', hero.id, error);
    } else {
      console.log('Successfully updated', hero.id);
    }
  }

  const progress = JSON.parse(fs.readFileSync('ai_parse_progress.json'));
  const idsToAdd = ['amira', 'laracroft', 'fluffy', 'dante', 'aidan', 'lyria', 'byrna'];
  idsToAdd.forEach(id => {
      if (!progress.includes(id)) progress.push(id);
  });
  fs.writeFileSync('ai_parse_progress.json', JSON.stringify(progress, null, 2));
  console.log('Progress file updated');
}

updateHeroes();
