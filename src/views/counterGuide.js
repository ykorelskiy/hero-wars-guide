export function getHeroIcon(name) {
  if (!name) return "";
  const norm = name.toLowerCase().replace(/[^a-z]/g, "");
  if (norm === "astridandlucas" || norm === "astrid") return "/assets/heroes/astrid.png";
  if (norm === "biscuit") return "/images/pets/biscuit.png";
  if (norm === "laracroft") return "/assets/heroes/laracroft.png";
  if (norm === "qingmao") return "/assets/heroes/qingmao.png";
  return "/assets/heroes/" + norm + ".png";
}

