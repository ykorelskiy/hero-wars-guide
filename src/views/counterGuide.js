export function showCounterTab(tab) {
  currentTab = tab;
  const container = document.getElementById("view-counter-guide");
  if (!container) return;

  container.querySelectorAll("nav.cg-tabs [role=tab]").forEach(b => {
    b.setAttribute("aria-selected", b.dataset.tab === tab);
  });

  const viewEl = document.getElementById("cgView");
  if (!viewEl) return;

  viewEl.innerHTML = THREATS[tab] ? renderThreat(tab) : (TABS[tab] ? TABS[tab]() : renderBasics());

  // Search bind for arena heroes
  bindSearch();
}

function bindSearch() {
  const s = document.getElementById("cgHeroSearch");
  if (s) {
    s.addEventListener("input", e => {
      window.__cg_q = e.target.value;
      const pos = e.target.selectionStart;
      const viewEl = document.getElementById("cgView");
      if (viewEl) viewEl.innerHTML = renderArenaHeroes();
      const n = document.getElementById("cgHeroSearch");
      if (n) {
        n.focus();
        n.setSelectionRange(pos, pos);
      }
      bindSearch();
    });
  }
}

function buildRoster() {
  const rosterEl = document.getElementById("cgRoster");
  if (!rosterEl) return;

  const names = new Set();
  Object.values(THREATS).forEach(t => t.counters.forEach(c => names.add(c.hero)));
  ARENA_HEROES.forEach(x => names.add(x.n));

  rosterEl.innerHTML = [...names].sort().map(n => {
    const icon = getHeroIcon(n);
    return `
      <label class="roster-item">
        <input type="checkbox" value="${n}" ${mine.has(n) ? "checked" : ""}>
        ${icon ? `<img src="${icon}" alt="${n}" class="roster-avatar" onerror="this.style.display='none'">` : ""}
        <span>${n}${HEROES[n] && HEROES[n].ru ? ` (${HEROES[n].ru})` : ""}</span>
      </label>
    `;
  }).join("");

  rosterEl.addEventListener("change", e => {
    if (e.target.type !== "checkbox") return;
    e.target.checked ? mine.add(e.target.value) : mine.delete(e.target.value);
    store("hwde-mine", [...mine]);
    showCounterTab(currentTab);
  });
}

export function initCounterGuideView() {
  if (isInitialized) return;
  isInitialized = true;

  mine = new Set(load("hwde-mine", []));

  const onlyMineBtn = document.getElementById("cgOnlyMine");
  if (onlyMineBtn) {
    onlyMineBtn.addEventListener("click", e => {
      onlyMine = !onlyMine;
      e.currentTarget.setAttribute("aria-pressed", onlyMine);
      e.currentTarget.textContent = onlyMine ? "Показывать всех" : "Показывать только моих";
      e.currentTarget.classList.toggle("on", onlyMine);
      showCounterTab(currentTab);
    });
  }

  const clearMineBtn = document.getElementById("cgClearMine");
  if (clearMineBtn) {
    clearMineBtn.addEventListener("click", () => {
      mine.clear();
      store("hwde-mine", []);
      buildRoster();
      showCounterTab(currentTab);
    });
  }

  const navTabs = document.querySelector(".counter-guide-wrap nav.cg-tabs");
  if (navTabs) {
    navTabs.addEventListener("click", e => {
      const b = e.target.closest("[role=tab]");
      if (b && b.dataset.tab) {
        showCounterTab(b.dataset.tab);
        // Scroll horizontally if needed so active tab is in view
        b.scrollIntoView({ behavior: "smooth", block: "nearest", inline: "center" });
      }
    });
  }

  buildRoster();
  showCounterTab("basics");
}
